-- Модуль 2 / триал: 7-дневный бесплатный пробный период с момента регистрации.
-- Запись user_subscriptions создаётся при первом заходе в кабинет (сразу после
-- регистрации), поэтому новый столбец trial_ends_at со значением по умолчанию
-- now() + 7 дней автоматически даёт каждому новичку неделю полного доступа.
--
-- Аддитивно: только новый столбец + бэкофилл существующих строк. isActive()
-- на фронте начинает учитывать триал; квоты бесплатного тарифа сохраняются как
-- запасной режим после окончания пробного периода.

alter table public.user_subscriptions
  add column if not exists trial_ends_at timestamptz default (now() + interval '7 days');

-- Бэкофилл для уже существующих подписок: неделя от даты создания записи.
-- Для старых аккаунтов срок, скорее всего, уже в прошлом — это корректно
-- (их пробный период давно прошёл), полный доступ остаётся по is_paid/admin.
update public.user_subscriptions
set trial_ends_at = created_at + interval '7 days'
where trial_ends_at is null;

comment on column public.user_subscriptions.trial_ends_at is
  'Окончание 7-дневного бесплатного пробного периода (с момента регистрации).';
