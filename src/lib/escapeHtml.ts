/**
 * Экранирование текста для вставки в HTML-строку — и в содержимое тега, и в
 * значение атрибута (поэтому кавычки экранируются тоже).
 *
 * Нужно там, где разметка собирается строкой, а не через DOM: DOMPurify
 * чистит готовый HTML, но не защищает от подстановки в шаблон. Пример из
 * кабинета — окно печати документа: его заголовок берётся из названия
 * документа, а название приходит из имени загруженного файла и ответа ИИ,
 * то есть задаётся пользователем.
 *
 * Отдельным модулем, чтобы потребителю не приходилось тянуть DOMPurify.
 */
export const escapeHtml = (value: string): string =>
  value
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#39;");
