import { format } from "date-fns";

/**
 * Производственный календарь РФ (Модуль 4 — календарь).
 *
 * Содержит нерабочие праздничные дни по ст. 112 ТК РФ — они одинаковы из года
 * в год — и вычисляет выходные (суббота/воскресенье). Этого достаточно, чтобы
 * корректно подсветить подавляющее большинство нерабочих дней и не назначать
 * явку/подачу документов в день, когда госорганы закрыты.
 *
 * Правительственные «переносы выходных» (когда праздник выпадает на выходной и
 * день отдыха официально переносится на другую дату) задаются на конкретный год
 * в EXTRA_DAYS_OFF / WORKING_WEEKENDS по официальному постановлению. Логика
 * консервативна: если перенос не задан, день трактуется по общему правилу —
 * сами праздники и выходные всё равно отмечаются верно, может лишь не хватать
 * «бонусного» переноса. Списки переносов обновляются раз в год.
 */

// Фиксированные нерабочие праздничные дни, ключ — «ММ-ДД» (ст. 112 ТК РФ).
const FIXED_HOLIDAYS: Record<string, string> = {
  "01-01": "Новогодние каникулы",
  "01-02": "Новогодние каникулы",
  "01-03": "Новогодние каникулы",
  "01-04": "Новогодние каникулы",
  "01-05": "Новогодние каникулы",
  "01-06": "Новогодние каникулы",
  "01-07": "Рождество Христово",
  "01-08": "Новогодние каникулы",
  "02-23": "День защитника Отечества",
  "03-08": "Международный женский день",
  "05-01": "Праздник Весны и Труда",
  "05-09": "День Победы",
  "06-12": "День России",
  "11-04": "День народного единства",
};

// Дополнительные выходные по переносам, ключ — «ГГГГ-ММ-ДД».
// Заполняется из официального постановления Правительства на конкретный год.
const EXTRA_DAYS_OFF: Record<string, string> = {
  // Пример: "2026-01-09": "Перенос новогодних каникул",
};

// Рабочие субботы/воскресенья по переносам, «ГГГГ-ММ-ДД» — переопределяют выходной.
const WORKING_WEEKENDS: Set<string> = new Set<string>([
  // Пример: "2026-..."
]);

export type DayKind = "work" | "weekend" | "holiday";

export interface DayInfo {
  kind: DayKind;
  /** Нерабочий день (праздник или выходной без переноса). */
  isDayOff: boolean;
  /** Название праздника/переноса, если есть. */
  label?: string;
}

const mmdd = (d: Date) => format(d, "MM-dd");
const ymd = (d: Date) => format(d, "yyyy-MM-dd");

/** Тип дня по производственному календарю РФ. */
export function getDayInfo(date: Date): DayInfo {
  const key = ymd(date);

  const holidayName = FIXED_HOLIDAYS[mmdd(date)] ?? EXTRA_DAYS_OFF[key];
  if (holidayName) return { kind: "holiday", isDayOff: true, label: holidayName };

  const dow = date.getDay(); // 0 — воскресенье, 6 — суббота
  const isWeekend = (dow === 0 || dow === 6) && !WORKING_WEEKENDS.has(key);
  if (isWeekend) return { kind: "weekend", isDayOff: true };

  return { kind: "work", isDayOff: false };
}

export const isDayOff = (date: Date): boolean => getDayInfo(date).isDayOff;
export const isHoliday = (date: Date): boolean => getDayInfo(date).kind === "holiday";
