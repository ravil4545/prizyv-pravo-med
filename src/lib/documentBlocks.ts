//  Конструктор документа из блоков (§5 предложения).
//
//  Раньше «Мой шаблон» открывал пустое поле: юрист писал документ с нуля либо
//  копировал куски из готовых. Теперь документ собирается из типовых частей в
//  правильном порядке, а правовые основания берутся из библиотеки, а не
//  вспоминаются.
//
//  ГЛАВНОЕ АРХИТЕКТУРНОЕ РЕШЕНИЕ: конструктор ГЕНЕРИРУЕТ обычный bodyTemplate,
//  а не заводит параллельную структуру документа.
//  Почему так:
//    • всё существующее — предпросмотр, DOCX, PDF, печать, условные блоки —
//      продолжает работать без единой правки;
//    • юрист всё равно правит формулировки руками, и текст должен оставаться
//      источником правды;
//    • не нужна миграция БД под хранение блоков.
//  Плата: собранный документ нельзя «разобрать» обратно на блоки. Для сценария
//  «собрал каркас — дальше правлю текст» это приемлемо; если понадобится
//  редактирование блоками, структуру можно будет хранить в user_templates.
//
//  Все основания взяты из формулировок, уже используемых в каталоге шаблонов
//  (см. docTemplates.ts), а не сочинены заново.
// ════════════════════════════════════════════════════════════════════════

import { ACCEPT, APPENDIX, FROM_MED, FROM_MIL, SIGN } from "./docTemplates";

export type BlockKind =
  | "addressee"   // кому и от кого
  | "title"       // ЗАЯВЛЕНИЕ / ЖАЛОБА
  | "facts"       // фактические обстоятельства
  | "grounds"     // правовое основание
  | "demand"      // просительная часть
  | "appendix"    // приложения
  | "signature";  // подпись, дата, отметка о принятии

export interface DocumentBlock {
  id: string;
  kind: BlockKind;
  /** Подпись в конструкторе. */
  label: string;
  /** Короткое пояснение: когда этот блок нужен. */
  hint?: string;
  /** Текст с токенами {{ключ}} — вставляется в шаблон как есть. */
  body: string;
}

