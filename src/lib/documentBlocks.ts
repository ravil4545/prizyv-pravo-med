export const BLOCK_LIBRARY: DocumentBlock[] = [
  ...ADDRESSEE_BLOCKS,
  ...TITLE_BLOCKS,
  ...FACTS_BLOCKS,
  ...GROUNDS_BLOCKS,
  ...DEMAND_BLOCKS,
  ...CLOSING_BLOCKS,
];

export const blocksOfKind = (kind: BlockKind): DocumentBlock[] =>
  BLOCK_LIBRARY.filter((b) => b.kind === kind);

export const blockById = (id: string): DocumentBlock | undefined =>
  BLOCK_LIBRARY.find((b) => b.id === id);

/**
 * Собирает текст шаблона из выбранных блоков.
 *
 * Блоки сортируются по KIND_ORDER: порядок частей документа задан правилами
 * делопроизводства, а не желанием пользователя — «подпись сверху» не нужна
 * никому. Внутри одного вида сохраняется порядок выбора.
 *
 * Основание и просительная часть склеиваются в одно предложение: «На основании
 * … прошу:» — так они и написаны в готовых шаблонах.
 */
export function composeDocument(blockIds: string[]): string {
  const chosen = blockIds
    .map(blockById)
    .filter((b): b is DocumentBlock => Boolean(b));

  const ordered = KIND_ORDER.flatMap((kind) => chosen.filter((b) => b.kind === kind));
  if (!ordered.length) return "";

  const parts: string[] = [];
  for (let i = 0; i < ordered.length; i++) {
    const block = ordered[i];
    const next = ordered[i + 1];

    if (block.kind === "grounds" && next?.kind === "demand") {
      // «На основании ст. … прошу:» — одним предложением, как в каталоге.
      parts.push(`${block.body} ${next.body}`);
      i++; // просительную часть уже забрали
      continue;
    }
    parts.push(block.body);
  }

  return parts.join("\n\n");
}
