/**
 * Подборка документов для статьи. `category` — из disease_articles_565.
 * Неизвестный или пустой профиль трактуется как поликлиника: это самый частый
 * случай и он не вводит в заблуждение.
 */
export function templatesForArticle(category: string | null | undefined): SuggestedTemplate[] {
  const source = SOURCE_BY_CATEGORY[(category ?? "") as ArticleCategory] ?? POLYCLINIC;
  return [...source, ...UNIVERSAL];
}

/** Куда идти за выпиской — человеческим языком, для подписи над списком. */
export function medicalSourceLabel(category: string | null | undefined): string {
  if (category === "mental") return "психоневрологический диспансер (ПНД)";
  if (category === "skin") return "кожно-венерологический диспансер (КВД)";
  return "поликлиника по месту прикрепления";
}
