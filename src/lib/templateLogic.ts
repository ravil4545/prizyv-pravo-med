// ════════════════════════════════════════════════════════════════════════
//  Условные блоки и списки в шаблонах документов (§5 предложения).
//
//  Раньше шаблон был плоским: только подстановка {{ключ}}. Из-за этого на
//  каждый вариант ситуации приходилось заводить ОТДЕЛЬНЫЙ шаблон, и каталог
//  рос линейно: «заявление об отсрочке по учёбе», «…по семейным», «…и то и
//  другое»…
//
//  Три конструкции закрывают ~90% реальной потребности:
//
//    {{#if study_org}}
//      Обучаюсь в {{study_org}} по программе {{study_level}}.
//    {{/if}}
//
//    {{#unless has_documents}}
//      Прошу выдать направление на обследование.
//    {{/unless}}
//
//    {{#each docs_list}}
//      {{@index}}. {{this}}
//    {{/each}}
//
//  Реализовано без внешних зависимостей: Handlebars ради трёх конструкций —
//  лишние 20 КБ в бандле и целый язык шаблонов там, где нужен минимум.
//
//  ПРАВИЛА:
//  • «Истинность» = непустая строка после trim. Юридический документ не должен
//    зависеть от JS-приведения типов: строка "0" — это заполненное поле.
//  • {{#each}} работает по многострочному значению: каждая непустая строка —
//    элемент. Именно так пользователь заполняет «Приложения» в форме.
//  • Блоки вкладываются. Незакрытый блок НЕ ломает документ — остаётся текстом,
//    чтобы автор шаблона увидел свою ошибку, а не потерял абзац.
// ════════════════════════════════════════════════════════════════════════

// Внутри блока НЕ должно быть другого открывающего тега — так регулярка всегда
// находит САМЫЙ ВНУТРЕННИЙ блок и берёт парный ему закрывающий.
//
// Наивный вариант `([\s\S]*?)\{\{\/\1\}\}` разбирал вложенность неверно: на
// «{{#if a}}A{{#if b}}B{{/if}}{{/if}}» он останавливался на ПЕРВОМ {{/if}},
// оставляя второй мусором в документе. Поймано тестом «вложенные блоки».
const BLOCK_RE =
  /\{\{#(if|unless|each)\s+([a-zA-Z_][a-zA-Z0-9_]*)\s*\}\}((?:(?!\{\{#)[\s\S])*?)\{\{\/\1\}\}/;

/** Поле считается заполненным, если после trim осталось что-то кроме пустоты. */
export function isFilled(value: string | undefined | null): boolean {
  return typeof value === "string" && value.trim() !== "";
}

/** Разбивает многострочное значение на элементы списка. */
export function toListItems(value: string | undefined | null): string[] {
  if (!isFilled(value)) return [];
  return String(value)
    .split(/\r?\n/)
    .map((s) => s.trim())
    .filter(Boolean);
}

/**
 * Раскрывает условные блоки и циклы. Токены {{ключ}} НЕ трогает — их подставляет
 * renderTemplate следующим шагом, как и раньше.
 *
 * Обрабатывает вложенность: внутренние блоки раскрываются после внешних, потому
 * что регулярное выражение нежадное и на каждой итерации берёт первый
 * завершённый блок.
 */
export function expandBlocks(template: string, values: Record<string, string>): string {
  let out = template;
  // Потолок итераций — защита от патологических шаблонов; на реальных
  // документах хватает единиц проходов.
  for (let guard = 0; guard < 200; guard++) {
    const m = BLOCK_RE.exec(out);
    if (!m) break;

    const [full, kind, key, inner] = m;
    let replacement = "";

    if (kind === "if") {
      replacement = isFilled(values[key]) ? inner : "";
    } else if (kind === "unless") {
      replacement = isFilled(values[key]) ? "" : inner;
    } else {
      const items = toListItems(values[key]);
      replacement = items
        .map((item, i) =>
          inner
            .replace(/\{\{\s*@index\s*\}\}/g, String(i + 1))
            .replace(/\{\{\s*this\s*\}\}/g, item),
        )
        .join("\n");
    }

    out = out.slice(0, m.index) + replacement + out.slice(m.index + full.length);
  }

  return tidyBlankLines(out);
}

/**
 * После вырезания блоков остаются «дыры» из пустых строк. В юридическом
 * документе три пустые строки подряд выглядят как ошибка вёрстки, поэтому
 * схлопываем их до одной и подчищаем края.
 */
export function tidyBlankLines(text: string): string {
  return text
    .replace(/[ \t]+\n/g, "\n")
    .replace(/\n{3,}/g, "\n\n")
    .replace(/^\n+/, "")
    .replace(/\n+$/, "\n");
}

/**
 * Ключи, использованные в блочных конструкциях. Нужны редактору: поле «Место
 * учёбы» должно появиться в форме, даже если {{study_org}} встречается только
 * внутри {{#if study_org}} — иначе пользователь не сможет его заполнить и блок
 * никогда не раскроется.
 */
export function extractBlockKeys(template: string): string[] {
  const out: string[] = [];
  const re = /\{\{#(?:if|unless|each)\s+([a-zA-Z_][a-zA-Z0-9_]*)\s*\}\}/g;
  let m: RegExpExecArray | null;
  while ((m = re.exec(template)) !== null) {
    if (!out.includes(m[1])) out.push(m[1]);
  }
  return out;
}

/** Есть ли в шаблоне блочные конструкции — для подсказки в редакторе. */
export function hasBlocks(template: string): boolean {
  return /\{\{#(?:if|unless|each)\s+[a-zA-Z_]/.test(template);
}
