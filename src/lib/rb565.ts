// Расписание болезней (РБ-565) — справочные данные и разбор официального текста статьи.
//
// ИСТОЧНИК НАЗВАНИЙ: канонические официальные наименования статей берутся из «второго мозга»
// (rag_chunks, категория rb_official — section_title «Статья N — …»), а НЕ из колонки
// disease_articles_565.title, которая местами рассинхронизирована (напр. ст. 47 в базе названа
// «Геморрой», тогда как официально это «Нейроциркуляторная астения»). Здесь — источник истины
// для отображаемых на странице названий.
//
// Колонка body таблицы disease_articles_565 содержит официальный текст статьи (с изменениями,
// включая ПП РФ № 1314 от 29.08.2025). parseArticleBody() превращает этот «сырой» текст в
// структуру: пункты (а/б/в…) с категориями годности по графам I/II/III + пояснения.

export interface ParsedPoint {
  /** буква пункта: а, б, в … */
  letter: string;
  /** описание степени нарушения функции */
  description: string;
  /** категории годности по графам: [I, II, III]; токены вида «Д», «В», «Б-3», «Б (В - ИНД)» */
  graphs: string[];
}

export interface ParsedExplanation {
  /** заголовок раздела, напр. «Пункт «а»» */
  title: string;
  paragraphs: string[];
}

export interface ParsedArticle {
  /** структурная таблица пунктов и категорий */
  points: ParsedPoint[];
  /** разбор «К пункту „X“ относятся…» */
  pointExplanations: ParsedExplanation[];
  /** общие положения статьи (текст, не привязанный к конкретному пункту) */
  notes: string[];
  /** были ли в тексте отметки о редакциях (в ред. …) */
  hasEdits: boolean;
  /** удалось ли разобрать таблицу пунктов */
  hasStructure: boolean;
  /** очищенный текст, если структуру разобрать не удалось (короткие/неполные статьи) */
  fallbackText: string;
}

