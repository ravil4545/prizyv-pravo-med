/** Полное (официальное) наименование статьи. Fallback — значение из базы. */
export function articleFullName(num: string | number, fallback = ""): string {
  const key = String(num).trim();
  return RB_ARTICLE_NAMES[key] ?? fallback.trim();
}

/** Краткая подпись для оглавления (производная от полного названия). */
export function articleShortName(num: string | number, fallback = ""): string {
  const full = articleFullName(num, fallback);
  return shortenName(full);
}

/** Сжимает длинное официальное название до компактной подписи для списка. */
function shortenName(full: string): string {
  let s = full.trim();
  if (!s) return s;
  // обрезаем по концу первого предложения
  const periodIdx = s.indexOf(". ");
  if (periodIdx > 12 && periodIdx < 72) s = s.slice(0, periodIdx);
  // обрезаем по первой скобке-уточнению
  const parenIdx = s.indexOf(" (");
  if (parenIdx > 12 && parenIdx < 72) s = s.slice(0, parenIdx);
  if (s.length <= 62) return s;
  const head = s.slice(0, 62);
  const lastComma = head.lastIndexOf(",");
  if (lastComma > 28) return s.slice(0, lastComma) + "…";
  const lastSpace = head.lastIndexOf(" ");
  return s.slice(0, lastSpace > 28 ? lastSpace : 62) + "…";
}

